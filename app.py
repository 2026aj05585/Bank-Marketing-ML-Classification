"""Streamlit evaluation interface for the saved Bank Marketing classifiers.

This app never trains or refits a model. It only loads serialized pipelines
created by train.py and evaluates an uploaded labelled test CSV.
"""
from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import (accuracy_score, roc_auc_score, precision_score,
                             recall_score, f1_score, matthews_corrcoef,
                             confusion_matrix, classification_report)

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "models"
TARGET = "y"
MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "svm.joblib",
}

st.set_page_config(page_title="Bank Marketing | Model Evaluation", page_icon="📊", layout="wide")
st.title("Bank Marketing Subscription — Model Evaluation")
st.caption("Compare five saved classifiers using a labelled CSV test set. Models are loaded from disk; no retraining occurs here.")

available = {name: path for name, filename in MODEL_FILES.items()
             if (path := MODEL_DIR / filename).exists()}
if not available:
    st.error("No trained models found. Run `python train.py` first and commit the generated models/ folder.")
    st.stop()

uploaded = st.file_uploader("Upload test data (CSV)", type=["csv"], help="The CSV must contain all model input columns and the target column 'y' with yes/no labels.")
if uploaded is None:
    default_path = ROOT / "test_data.csv"
    if default_path.exists():
        st.info("No file uploaded. Using the project's generated test_data.csv.")
        data = pd.read_csv(default_path)
    else:
        st.info("Upload the labelled test_data.csv generated by train.py to begin.")
        st.stop()
else:
    try:
        data = pd.read_csv(uploaded)
    except Exception as exc:
        st.error(f"Could not read CSV: {exc}")
        st.stop()

if TARGET not in data.columns:
    st.error("The uploaded CSV must include the target column 'y'.")
    st.stop()
if data.empty:
    st.error("The uploaded CSV contains no rows.")
    st.stop()

X = data.drop(columns=[TARGET, "duration"], errors="ignore")
y_true = data[TARGET].astype(str).str.strip().str.lower()
if not set(y_true.unique()).issubset({"yes", "no"}):
    st.error("Target column 'y' must contain only 'yes' and 'no'.")
    st.stop()

# Validate columns against the saved pipeline before attempting prediction.
selected_name = st.selectbox("Choose a classifier", list(available.keys()))
selected_model = joblib.load(available[selected_name])
expected = list(selected_model.named_steps["preprocessor"].feature_names_in_)
missing = [column for column in expected if column not in X.columns]
if missing:
    st.error("Missing required input columns: " + ", ".join(missing))
    st.stop()
X = X[expected]


def evaluate(name, model):
    predictions = model.predict(X)
    scores = model.predict_proba(X)[:, 1] if hasattr(model, "predict_proba") else model.decision_function(X)
    metrics = {
        "Model": name,
        "Accuracy": accuracy_score(y_true, predictions),
        "AUC": roc_auc_score(y_true, scores),
        "Precision": precision_score(y_true, predictions, pos_label="yes", zero_division=0),
        "Recall": recall_score(y_true, predictions, pos_label="yes", zero_division=0),
        "F1": f1_score(y_true, predictions, pos_label="yes", zero_division=0),
        "MCC": matthews_corrcoef(y_true, predictions),
    }
    return metrics, predictions

results = []
for name, path in available.items():
    model = selected_model if name == selected_name else joblib.load(path)
    row, _ = evaluate(name, model)
    results.append(row)
results_df = pd.DataFrame(results).set_index("Model")

st.subheader("Dataset overview")
col1, col2, col3 = st.columns(3)
col1.metric("Test records", f"{len(data):,}")
col2.metric("Input features", f"{len(expected)}")
col3.metric("Positive class rate", f"{(y_true == 'yes').mean():.1%}")

st.subheader("Comparison of all available models")
st.dataframe(results_df.style.format("{:.4f}"), use_container_width=True)

selected_metrics, selected_predictions = evaluate(selected_name, selected_model)
st.subheader(f"Selected model: {selected_name}")
metric_cols = st.columns(6)
for col, metric in zip(metric_cols, ["Accuracy", "AUC", "Precision", "Recall", "F1", "MCC"]):
    col.metric(metric, f"{selected_metrics[metric]:.4f}")

st.subheader("Confusion matrix")
cm = confusion_matrix(y_true, selected_predictions, labels=["no", "yes"])
fig, ax = plt.subplots(figsize=(5, 4))
ax.imshow(cm)
ax.set_xticks([0, 1], labels=["Predicted no", "Predicted yes"])
ax.set_yticks([0, 1], labels=["Actual no", "Actual yes"])
ax.set_xlabel("Prediction")
ax.set_ylabel("Actual")
ax.set_title("Confusion Matrix")
for (i, j), value in __import__("numpy").ndenumerate(cm):
    ax.text(j, i, str(value), ha="center", va="center")
st.pyplot(fig)
plt.close(fig)

st.subheader("Classification report")
report = classification_report(y_true, selected_predictions, labels=["no", "yes"],
                               target_names=["No subscription", "Subscription"],
                               output_dict=True, zero_division=0)
st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

st.download_button("Download evaluated metrics (CSV)", results_df.reset_index().to_csv(index=False),
                   file_name="uploaded_test_metrics.csv", mime="text/csv")
